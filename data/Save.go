package data

import (
	"bank/structs"
	"encoding/json"
	"bank/cards"
	"fmt"
	"os"
)

func SaveFileJson(bank *structs.Bank)(error){

	file, err := json.MarshalIndent(bank, "","    " )
		if err != nil{return err}

	err = os.WriteFile("Data/bank.json", file, 0777)
		if err != nil{return err}

	return nil

}


func ReadFileJson(bank *structs.Bank) error {           // Загружает банк из JSON и возвращает ошибку при сбое.
    file, err := os.ReadFile("Data/bank.json")          // Читает файл в срез байтов.
    if err != nil {                                     // Проверяет ошибку чтения файла.
        fmt.Println("Ошибка 1")                         // Выводит сообщение об ошибке чтения.
        return err                                      // Возвращает ошибку чтения.
    }                                                   // Конец проверки ошибки чтения.

    err = json.Unmarshal(file, bank)                    // Заполняет банк; карты в any пока становятся map[string]any.
    if err != nil {                                     // Проверяет ошибку распаковки банка.
        fmt.Println("Ошибка 2")                         // Выводит сообщение об ошибке распаковки банка.
        return err                                      // Возвращает ошибку распаковки банка.
    }                                                   // Конец проверки ошибки распаковки банка.

    var sv struct {                                     // Объявляет временную структуру с исходными данными карт.
        Cards map[int]json.RawMessage                   // Хранит JSON каждой карты как срез байтов по её ID.
    }                                                   // Конец объявления временной структуры.
    err = json.Unmarshal(file, &sv)                     // Извлекает JSON карт во временную структуру.
    if err != nil {                                     // Проверяет ошибку извлечения карт.
        fmt.Println("Ошибка 3")                         // Выводит сообщение об ошибке извлечения карт.
        return err                                      // Возвращает ошибку извлечения карт.
    }                                                   // Конец проверки ошибки извлечения карт.

    for i, raw := range sv.Cards {                      // Перебирает ID карт и их JSON-данные.
        var inf struct {                                // Объявляет структуру для чтения типа карты.
            Type string                                 // Хранит тип текущей карты.
        }                                               // Конец объявления структуры типа карты.
        err = json.Unmarshal(raw, &inf)                 // Читает тип из JSON текущей карты.
        if err != nil {                                 // Проверяет ошибку чтения типа.
            fmt.Println("Ошибка 3")                     // Выводит сообщение об ошибке чтения типа.
            return err                                  // Возвращает ошибку чтения типа.
        }                                               // Конец проверки ошибки чтения типа.

        switch inf.Type {                               // Выбирает обработку по типу карты.
        case "Debit":                                   // Обрабатывает дебетовую карту.
            var card cards.Card                         // Объявляет структуру дебетовой карты.
            err = json.Unmarshal(raw, &card)            // Заполняет дебетовую карту из JSON.
            if err != nil {                             // Проверяет ошибку распаковки карты.
                fmt.Println("Ошибка 3")                 // Выводит сообщение об ошибке распаковки.
                return err                              // Возвращает ошибку распаковки.
            }                                           // Конец проверки ошибки распаковки.
            bank.Cards[i] = card                        // Записывает дебетовую карту вместо map в Cards.

        case "Credit":                                  // Обрабатывает кредитную карту.
            var ccard cards.CreditCard                  // Объявляет структуру кредитной карты.
            err = json.Unmarshal(raw, &ccard)           // Заполняет кредитную карту из JSON.
            if err != nil {                             // Проверяет ошибку распаковки карты.
                fmt.Println("Ошибка 3")                 // Выводит сообщение об ошибке распаковки.
                return err                              // Возвращает ошибку распаковки.
            }                                           // Конец проверки ошибки распаковки.
            bank.Cards[i] = ccard                       // Записывает кредитную карту вместо map в Cards.

        default:                                        // Обрабатывает неизвестный или отсутствующий тип.
            return err                                  // Завершает загрузку; здесь err равен nil после успешного Unmarshal.
        }                                               // Конец выбора типа карты.
    }                                                   // Конец перебора карт.

    return nil                                          // Сообщает об успешной загрузке.
}                                                       // Конец функции.
